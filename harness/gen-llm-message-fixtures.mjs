#!/usr/bin/env node
/**
 * Capture how pi turns context messages that are not conversation into messages a
 * provider can read.
 *
 * `convertToLlm` is the last step before a model sees the conversation, and it is
 * where a compaction summary stops being a `compactionSummary` record and becomes
 * a user turn wrapped in `<summary>` framing. That framing is part of the wire
 * format — a model has been tuned on it — and it is exactly the kind of string that
 * gets "tidied up" by hand, so it is captured rather than retyped.
 *
 * Worth knowing while reading the output: pi-ai itself has no idea what a
 * `compactionSummary` is. Handed one, it silently drops it. The conversion has to
 * happen before the request builder runs, which is what `core` does.
 *
 *   node harness/gen-llm-message-fixtures.mjs
 */
import { writeFileSync } from "node:fs";

const PI = "/opt/homebrew/lib/node_modules/@earendil-works/pi-coding-agent/dist/index.js";
const { convertToLlm } = await import(PI);

const T = 1700000000000;

const cases = [
  {
    name: "compaction_summary",
    about: "压缩摘要变成 user 回合，并带 <summary> 包装",
    agent: { role: "compactionSummary", summary: "## Goal\nship it", tokensBefore: 4096, timestamp: T },
  },
  {
    name: "branch_summary",
    about: "分支摘要的包装与压缩摘要不同，两个字符串都要对",
    agent: { role: "branchSummary", summary: "earlier attempt", fromId: "abc", timestamp: T },
  },
  {
    name: "custom_parts",
    about: "custom 消息 content 是数组时原样传递",
    agent: { role: "custom", customType: "hook", content: [{ type: "text", text: "injected" }], display: false, timestamp: T },
  },
  {
    name: "custom_string",
    about: "custom 消息 content 是字符串时包成一个 text part",
    agent: { role: "custom", customType: "hook", content: "plain string", display: false, timestamp: T },
  },
];

const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");

const lines = [
  "///|",
  "/// How context messages that are not conversation reach a provider, captured",
  "/// from pi's `convertToLlm`.",
  "///",
  "/// Generated by `harness/gen-llm-message-fixtures.mjs`; do not edit by hand.",
  "///",
  "/// Each entry is (name, input JSON, expected message JSON). The input is the",
  "/// context message as pi records it; the expected value is what a provider",
  "/// actually receives.",
  "pub let llm_message_fixtures : Array[(String, String, String)] = [",
];

for (const { name, about, agent } of cases) {
  const [expected] = convertToLlm([agent]);
  if (!expected) throw new Error(`${name}: pi dropped the message`);
  lines.push("  (");
  lines.push(`    "${name}",`);
  lines.push(`    "${esc(JSON.stringify(agent))}",`);
  lines.push(`    "${esc(JSON.stringify(expected))}",`);
  lines.push(`  ),`);
  console.log(`${name.padEnd(20)} -> ${JSON.stringify(expected.content).slice(0, 70)}`);
}
lines.push("]");

writeFileSync("core/llm_message_fixtures.mbt", lines.join("\n") + "\n");
console.log(`\nwrote core/llm_message_fixtures.mbt (${cases.length} fixtures)`);
