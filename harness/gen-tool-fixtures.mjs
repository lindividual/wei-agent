#!/usr/bin/env node
/**
 * Generate tool-declaration fixtures from pi.
 *
 * A tool's description and parameter schema are prompt text: they tell the model
 * what the tool does and how to call it. Copying them is only correct if they
 * actually match, so they are captured from pi rather than transcribed.
 *
 * The name mapping is the one intentional difference: this project calls the
 * glob-search tool `glob`, pi calls it `find`.
 *
 *   node harness/gen-tool-fixtures.mjs
 */
import { readFileSync, existsSync, writeFileSync } from "node:fs";

const TOOLS_DIR =
  "/opt/homebrew/lib/node_modules/@earendil-works/pi-coding-agent/dist/core/tools";

const mod = await import(`${TOOLS_DIR}/index.js`);

/** our name -> pi's factory */
const FACTORIES = {
  bash: "createBashToolDefinition",
  read: "createReadToolDefinition",
  write: "createWriteToolDefinition",
  edit: "createEditToolDefinition",
  glob: "createFindToolDefinition",
  grep: "createGrepToolDefinition",
};

const entries = [];
for (const [name, factory] of Object.entries(FACTORIES)) {
  const build = mod[factory];
  if (typeof build !== "function") {
    throw new Error(`missing factory ${factory}`);
  }
  const tool = build("/tmp");
  entries.push({
    name,
    piName: tool.name,
    description: tool.description,
    parameters: tool.parameters,
  });
  console.log(
    `${name.padEnd(6)} (pi: ${tool.name.padEnd(6)}) params=${Object.keys(tool.parameters.properties ?? {}).length} desc=${tool.description.length}c`,
  );
}

const esc = (s) =>
  s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");

const lines = [
  "///|",
  "/// Tool declarations captured from pi.",
  "///",
  "/// Generated by `harness/gen-tool-fixtures.mjs`; do not edit by hand.",
  "///",
  "/// Each entry is (our name, pi's name, description, parameters JSON). The two",
  "/// names differ only for the glob-search tool, which pi calls `find`.",
  "pub let pi_tool_fixtures : Array[(String, String, String, String)] = [",
];
for (const e of entries) {
  lines.push("  (");
  lines.push(`    "${e.name}",`);
  lines.push(`    "${e.piName}",`);
  lines.push(`    "${esc(e.description)}",`);
  lines.push(`    "${esc(JSON.stringify(e.parameters))}",`);
  lines.push("  ),");
}
lines.push("]");

writeFileSync("core/tool_fixtures.mbt", lines.join("\n") + "\n");
console.log(`\nwrote core/tool_fixtures.mbt (${entries.length} tools)`);
